"""Accepted-lock, disposable-only token verification; no live App or repairs."""
import hashlib
import argparse
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[2]
DEPARTURES = {
    "package-lock.json": "caf5cbce73ec535033e36984f2c5d00e080a7a91c1575750b7008f7c52e9107e",
    "SETUP.md": "0226c80b675a0fab6c4df22b562013ceafd42bb8d60d5d0355a2642cb9a392e6",
    "replit.md": "a92e1ae7924aaf64eb78b69e48ea94f81c6998463017a8980244dc1680447e24",
    "server/index.ts": "2eee6c655d508e045a980256d4aa57624ce3c336ac9fe0758d6b0b003fc6d64d",
}
def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

rows = re.findall(r"^\| `([^`]+)` \| (\d+) \| `([0-9a-f]{64})` \|",
                  (ROOT / "docs/architecture-audit/baseline.md").read_text(), re.M)
assert len(rows) == 174
before = {}
parser = argparse.ArgumentParser()
parser.add_argument("--baseline", type=Path, help="Explicitly approved, pinned source manifest; never generated by this runner")
args = parser.parse_args()
approved = json.loads(args.baseline.read_text()) if args.baseline else None
if approved:
    historical_paths = {n for n, _, _ in rows}
    current_sources = {str(p.relative_to(ROOT)) for directory in ["client", "server", "shared"]
                       for p in (ROOT / directory).rglob("*") if p.is_file()}
    assert set(approved["files"]) == historical_paths | current_sources, "Unpinned source or baseline manifest scope changed"
    for name in ["package.json", "package-lock.json", "client/src/styles/design-tokens.css",
                 "client/src/lib/design-tokens.ts", "client/src/index.css",
                 "tailwind.config.ts", "client/src/pages/design-system.tsx"]:
        original = next(h for n, _, h in rows if n == name)
        assert approved["files"][name] == DEPARTURES.get(name, original), f"Unapproved contract change: {name}"
checks = {n: DEPARTURES.get(n, h) for n, _, h in rows}
if approved:
    checks = approved["files"]
for name, expected in checks.items():
    p = ROOT / name
    assert p.is_file() and not p.is_symlink(), name
    before[name] = digest(p)
    assert before[name] == expected, f"Unreconciled drift: {name}"
# Prove the server departure is exactly the independently approved logging edit.
server = (ROOT / "server/index.ts").read_text()
start = server.index("app.use((req, res, next) => {")
end = server.index("\n(async () => {", start)
old = (ROOT / "verification/api-logging/baseline-middleware.txt").read_text().rstrip()
reconstructed = server[:start] + old + "\n" + server[end:]
assert hashlib.sha256(reconstructed.encode()).hexdigest() == dict(
    (n, h) for n, _, h in rows)["server/index.ts"]

work = Path(tempfile.mkdtemp(prefix="token-verification-"))
copy = work / "copy"
for name in before:
    target = copy / name
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(ROOT / name, target)
for suite in ["baseline", "tokens"]:
    shutil.copytree(ROOT / "verification" / suite, copy / "verification" / suite)
env = {"PATH": os.environ["PATH"], "HOME": str(work / "home"), "TMPDIR": str(work),
       "TZ": "UTC", "LANG": "C.UTF-8", "CI": "true",
       "npm_config_cache": str(work / "cache"), "npm_config_userconfig": "/dev/null"}
Path(env["HOME"]).mkdir()
results = {"before": before, "commands": [], "reconciled_departures": DEPARTURES,
           "node": subprocess.check_output(["node", "--version"], env=env, text=True).strip()}
if approved:
    results["approved_baseline"] = {"path": str(args.baseline), "sha256": digest(args.baseline),
                                  "authorization": approved["authorization"]}
def run(label, argv, guarded=True):
    child = env.copy()
    if guarded:
        child["NODE_OPTIONS"] = "--require=" + str(copy / "verification/baseline/network-guard.cjs")
    with (work / (label + ".log")).open("w") as log:
        code = subprocess.run(argv, cwd=copy, env=child, stdout=log, stderr=subprocess.STDOUT).returncode
    results["commands"].append({"label": label, "argv": argv, "exit": code})
    print(label, code, flush=True)
    return code

print(work, flush=True)
try:
    if run("install", ["npm", "ci", "--ignore-scripts", "--no-audit", "--no-fund"], False) == 0:
        locked = json.loads((copy / "package-lock.json").read_text())["packages"]
        versions = {}
        for name, entry in locked.items():
            if not name:
                continue
            manifest = copy / name / "package.json"
            installed = json.loads(manifest.read_text())["version"] if manifest.exists() else None
            assert installed == entry.get("version") or (installed is None and entry.get("optional")), name
            versions[name] = installed
        results["installed_versions"] = versions
        run("authored", ["node", "verification/tokens/check.mjs"])
        # Same untouched full production content scan in both emissions.
        for label in ["baseline", "candidate"]:
            run("css-" + label, ["node", "node_modules/tailwindcss/lib/cli.js",
                "-c", "tailwind.config.ts", "-i", "client/src/index.css",
                "-o", str(work / (label + ".css"))])
        if all((work / (n + ".css")).exists() for n in ["baseline", "candidate"]):
            results["emitted_css"] = {n: digest(work / (n + ".css")) for n in ["baseline", "candidate"]}
            results["emitted_css_equal"] = len(set(results["emitted_css"].values())) == 1
finally:
    results["source_unchanged"] = all(digest(ROOT / n) == h for n, h in before.items())
    results["copy_unchanged"] = all(digest(copy / n) == h for n, h in before.items())
    (work / "results.json").write_text(json.dumps(results, indent=2) + "\n")
    print("Source/copy unchanged:", results["source_unchanged"], results["copy_unchanged"], flush=True)
raise SystemExit(0 if results["source_unchanged"] and results["copy_unchanged"]
                 and results.get("emitted_css_equal")
                 and all(c["exit"] == 0 for c in results["commands"]) else 1)
